export function getCampusImageForCollege(code?: string | null, slug?: string | null, name?: string): string {
  if (code && campusImagesByCollege[code.toLowerCase()]) {
    return campusImagesByCollege[code.toLowerCase()];
  }

  if (slug) {
    const slugLower = slug.toLowerCase();
    for (const [key, img] of Object.entries(campusImagesByCollege)) {
      if (slugLower.includes(key)) return img;
    }
  }

  if (name) {
    const nameLower = name.toLowerCase();
    for (const [key, img] of Object.entries(campusImagesByCollege)) {
      if (nameLower.includes(key)) return img;
    }

    // Deterministic variety based on college name hash
    let hash = 0;
    for (let i = 0; i < name.length; i++) {
      hash = (hash << 5) - hash + name.charCodeAt(i);
      hash |= 0;
    }
    const index = Math.abs(hash) % defaultCampusVarieties.length;
    return defaultCampusVarieties[index];
  }

  return defaultCampusVarieties[0];
}
