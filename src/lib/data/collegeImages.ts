export function getCampusImageForCollege(code?: string | null, slug?: string | null, name?: string): string {
  if (code) {
    const c = String(code).trim().toLowerCase();
    if (campusImagesByCollege[c]) return campusImagesByCollege[c];
  }

  if (slug) {
    const s = slug.trim().toLowerCase();
    if (campusImagesByCollege[s]) return campusImagesByCollege[s];
    for (const [key, img] of Object.entries(campusImagesByCollege)) {
      if (s.includes(key)) return img;
    }
  }

  if (name) {
    const n = name.trim().toLowerCase();
    for (const [key, img] of Object.entries(campusImagesByCollege)) {
      if (n.includes(key)) return img;
    }
    // Deterministic fallback
    let hash = 0;
    for (let i = 0; i < n.length; i++) {
      hash = (hash << 5) - hash + n.charCodeAt(i);
      hash |= 0;
    }
    return aiCampusGallery[Math.abs(hash) % aiCampusGallery.length];
  }

  return aiCampusGallery[0];
}
